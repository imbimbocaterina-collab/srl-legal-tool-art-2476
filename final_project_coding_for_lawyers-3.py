import os # Python Standard Library module that provides operating system interfaces to verify file existence and runtime errors
import re # Python Standard Library module that allows to work with Regular Expressions (Regex) - map text by its predictable structure allowing automation without knowing the exact sting before

"""1st step => automatic redaction using Regex"""

def apply_privacy_filters (text) :
# This function allows to mask personal data and amounts throughout Regular Expression


# The function will find and substitue in the text the standard alphanumeric
    # pattern for Italian fiscal code and censore it with 'omissis cf'
    text = re.sub (r'\b[A-Z]{6}\d{2}[A-Z]\d{2}[A-Z]\d{3}[A-Z]\b', "[OMISSIS_CF]", text)

# The function will then find and substitue in the text the standard sequence
    # for IBANs and censore it with 'omissis iban'
    text = re.sub (r'\bIT\d{2}[A-Z]\d{10}[A-Z0-9]{12}\b', "[OMISSIS_IBAN]", text)

# Finally the function censores monetary values recognized in the text
    text = re.sub (r'\d{1,3}(\.\d{3})*,\d{2}\s?€', "[VALUE_OMISSIS]", text )

    return text

"""2nd step => manual redaction for trade secrets"""

def manual_redaction (text) :
# This function allows the user to actively interact with the text and hide the trade secrets

# Prints the section header for the administrator interface
    print ("\n--- TRADE SECRET PROTECTION ---")
    print ("Identify the parts that contain trade secrets that non-managing shareholders should not view")

# Creates a new variable equal to the text to perform the modifications
    modified_text = text

# Infinte loop to allow infinte possible redactions
    while True :

# The input function pauses the program execution while the
        # administrator types a word or phrase, which is then stored in the
        # variable 'target'
        target = input ("\nEnter word/phrase to redact (or type 'done' to finalize) : ")

# Checks if the user typed 'done'. If so, the loop stops immediately
        if target.lower () == 'done' :
            break
# The function will check if the target string exists in the document
        # and replaces it with the legal compliance tag
        if target in modified_text:
            modified_text = modified_text.replace (target, "[OMISSIS - TRADE SECRET EX ART. 2476 c.c.]")
            print (f"'{target}' successfully redacted.")

# Handles missing search terms or typos without breaking program execution
        else:
            print ("Text not found in document. Please try again.")

# Returns final document
    return modified_text

"""3rd step => output"""

def save_compliant_document(text, file_name):
# This function allows to create a new file with the compliant text

# The new file will have a new name so that it won't be confused with the
    # original
    output_name = "inspection_" + os.path.basename (file_name)

# Safely opens the target file in write mode using UTF-8 encoding
    with open(output_name, "w", encoding="utf-8") as f:
# Writes the fully redacted text into the file
        f.write(text)

# Prints a confirmation message for the administrator
    print(f"\n[SUCCESS] document ready for shareholder inspection: {output_name}")

